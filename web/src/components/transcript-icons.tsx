export function toolIconKind(name: string): ActivityIconKind {
  const key = name.toLowerCase();
  if (["bash", "shell", "terminal", "exec_command"].includes(key)) return "terminal";
  if (["read", "readfile", "read_file", "get_worker_output", "taskoutput"].includes(key)) return "file";
  if (["edit", "write", "multiedit", "apply_patch"].includes(key)) return "edit";
  if (["grep", "ripgrep", "search", "websearch", "web_search"].includes(key)) return "search";
  if (["glob", "ls", "list_directory"].includes(key)) return "folder";
  if (["webfetch", "web_fetch", "fetch"].includes(key)) return "globe";
  if (["todowrite", "updatetodo", "update_plan"].includes(key)) return "plan";
  return "tool";
}

